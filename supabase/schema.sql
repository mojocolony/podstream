-- v0.2.6: persistent per-user episode archive. Episodes are retained even
-- when a publisher later shortens the current RSS feed.
create table if not exists public.podstream_episode_archive (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  episode_id text not null,
  show_id text not null,
  feed_url text,
  show_title text,
  title text,
  audio_url text not null,
  published_at timestamptz,
  duration_seconds double precision not null default 0 check (duration_seconds >= 0),
  image_url text,
  source text not null default 'rss',
  first_seen_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (user_id, episode_id)
);

alter table public.podstream_episode_archive enable row level security;
revoke all on table public.podstream_episode_archive from anon, authenticated;
grant select, insert, update, delete on table public.podstream_episode_archive to authenticated;
grant usage, select on sequence public.podstream_episode_archive_id_seq to authenticated;

create policy "Podstream users read own episode archive" on public.podstream_episode_archive
  for select to authenticated using ((select auth.uid()) = user_id);
create policy "Podstream users insert own episode archive" on public.podstream_episode_archive
  for insert to authenticated with check ((select auth.uid()) = user_id);
create policy "Podstream users update own episode archive" on public.podstream_episode_archive
  for update to authenticated using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id);
create policy "Podstream users delete own episode archive" on public.podstream_episode_archive
  for delete to authenticated using ((select auth.uid()) = user_id);

create index if not exists podstream_episode_archive_user_show_idx
  on public.podstream_episode_archive (user_id, show_id);
create index if not exists podstream_episode_archive_user_published_idx
  on public.podstream_episode_archive (user_id, published_at desc);

alter table public.podstream_subscriptions add column if not exists catalog_total integer;
alter table public.podstream_subscriptions add column if not exists backfilled_at timestamptz;
